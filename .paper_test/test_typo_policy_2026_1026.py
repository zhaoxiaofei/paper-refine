#!/usr/bin/env python3
"""Inferable-typo policy: correct the typo, then ask for a low-priority check.

Run:  python3 .paper_test/test_typo_policy_2026_1026.py

A typographical error whose correct form is determinable from the manuscript or
its public record (the printed author list and affiliations, raw data, the
deposited tables, the reference list, a DOI resolver, a standard email domain)
is a correctable error, not an `author-only` fact to defer:

* the revision corrects it and records the basis in CHANGELOG.md;
* MANUAL_STEPS.md carries ONE `priority=low` re-verification item naming the
  corrected value and the basis;
* high priority stays the `[AUTHOR TO COMPLETE: ...]` placeholder;
* grammar, punctuation and style edits are corrected in text and are NEVER
  listed in MANUAL_STEPS.md; a typo with no inferable basis keeps the
  `author-only` treatment.

The suite pins the rule in the three stage-prompt templates and the revise
skill, and in a prompt actually generated by `setup`/`run` with the stub agent.
"""
from __future__ import annotations

import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

WS = Path(os.environ.get("PAPER_WS") or Path(__file__).resolve().parent.parent)
STUB = WS / ".paper_test" / "stub_agent.py"
MARKER = "INFERABLE TYPOS ARE CORRECTED, NOT DEFERRED"
FAILS: list[str] = []
TMPDIRS: list[Path] = []


def check(name: str, cond: bool, detail: str = "") -> None:
    print(f"[{'ok ' if cond else 'FAIL'}] {name}" + (f"  -- {detail}" if detail else ""))
    if not cond:
        FAILS.append(name)


def scratch(prefix: str) -> Path:
    d = Path(tempfile.mkdtemp(prefix=prefix))
    TMPDIRS.append(d)
    return d


def load(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def run(args, **kw):
    return subprocess.run(
        [sys.executable, str(WS / "paper_pipeline.py"), *args],
        capture_output=True, text=True, timeout=1200, **kw,
    )


def make_source(tmp: Path) -> Path:
    src = tmp / "source"
    src.mkdir(parents=True)
    (src / "manuscript-o.md").write_text(
        "# Title\n\nA stub manuscript for the typo-policy test.\n", encoding="utf-8")
    return src


def test_static():
    print("\n== the rule is in the templates and the skill ==")
    p02 = (WS / "paper_pipeline_parts" / "p02_journal_modes.py").read_text(encoding="utf-8")
    check("all three stage-prompt templates carry the rule", p02.count(MARKER) == 3,
          f"found {p02.count(MARKER)}")
    check("the prompt states 'In a revision stage'", "In a revision stage" in p02)
    check("review/audit stages are stage-safe",
          "A review or audit stage reports the typo" in p02)
    check("grammar/punctuation/style are excluded",
          "Grammar, punctuation and style errors" in p02 and "NEVER listed" in p02)
    check("an unfounded typo keeps author-only", "keep the\n        `author-only` treatment" in p02)

    prompt = (WS / "paper-skills" / "prompts" / "adress_issues.prompt.md").read_text(encoding="utf-8")
    rules = (WS / "paper-skills" / "paper-revise" / "references" / "edit_rules.md").read_text(encoding="utf-8")
    skill = (WS / "paper-skills" / "paper-revise" / "SKILL.md").read_text(encoding="utf-8")
    check("the revise prompt carries the rule", MARKER in prompt)
    check("the edit rules carry the rule", MARKER in rules)
    for name, text in (("revise prompt", prompt), ("revise skill", skill)):
        check(f"{name}: low priority is defined", "priority=low" in text)
        check(f"{name}: high priority is the placeholder", "[AUTHOR TO COMPLETE: ...]" in text)
        check(f"{name}: low items ask for re-verification", "re-verify" in text)
    check("low priority never blocks", "never blocks" in prompt)
    check("the low-priority section convention is documented",
          "Low-priority re-verification (corrected in text)" in prompt)
    check("grammar/punctuation edits are never manual items",
          "never listed" in prompt and "not manual items" in prompt)


def test_generated_prompts():
    print("\n== a real setup/run generates prompts carrying the rule ==")
    tmp = scratch("typo_policy_")
    src = make_source(tmp)
    root = tmp / "root"
    r = run(["setup", "--source", str(src), "--root", str(root), "--rounds", "1",
             "--judges", "1", "--rewrites", "0", "--revises", "1", "--integrators", "1"])
    check("setup succeeds", r.returncode == 0, (r.stderr or r.stdout)[-300:])
    if r.returncode != 0:
        return
    r = run(["run", "--root", str(root), "--agent-cmd",
             json.dumps([sys.executable, str(STUB)]), "--retries", "0"])
    check("the stub round completes", r.returncode == 0, (r.stdout or r.stderr)[-400:])
    if r.returncode != 0:
        return
    revise = (root / "runs" / "r1_a2_revise" / "PROMPT.md").read_text(encoding="utf-8")
    check("generated revise prompt carries the rule", MARKER in revise)
    check("generated revise prompt scopes the edit", "In a revision stage" in revise)
    check("generated revise prompt defines the priority split",
          "priority=low" in revise and "[AUTHOR TO COMPLETE: ...]" in revise)
    review = (root / "runs" / "r1_review" / "PROMPT.md").read_text(encoding="utf-8")
    check("generated review prompt reports rather than edits",
          "A review or audit stage reports the typo" in review)


def test_manual_counter():
    print("\n== the low-priority section is counted, not dropped ==")
    pp = load("typo_policy_pipeline", WS / "paper_pipeline.py")
    tmp = scratch("typo_manual_")
    path = tmp / "MANUAL_STEPS.md"
    path.write_text(
        "## 1. High priority\n\n"
        "| # | finding | what |\n|---|---|---|\n| 1 | F-001 | author-only fact |\n\n"
        "## Low-priority re-verification (corrected in text)\n\n"
        "| priority=low | file/location | before -> after | basis | what to re-verify |\n"
        "|---|---|---|---|---|\n"
        "| low | paper.md line 3 | mit.eud -> mit.edu | author list + standard domain | confirm |\n",
        encoding="utf-8")
    count = pp.count_manual_steps(path)
    check("both the high and the low item are counted", count == 2, f"count={count}")


def test_mode_destinations():
    print("\n== each author-to-complete mode keeps its own hand-off destination ==")
    pp = load("typo_policy_modes", WS / "paper_pipeline.py")
    doc = pp.placeholder_rule_text("document")
    readme = pp.placeholder_rule_text("readme")
    off = pp.placeholder_rule_text("off")
    check("document mode keeps the marker as the high-priority hand-off",
          "High priority is a `[AUTHOR TO COMPLETE: ...]` placeholder"
          in " ".join(doc.split()))
    check("off mode never offers the forbidden marker as the high-priority hand-off",
          "never a `[AUTHOR TO COMPLETE: ...]` placeholder" in off)
    check("readme mode sends the low-priority item to the hand-off README",
          "priority is a row in `README-AUTHOR-TO-COMPLETE.md`" in readme
          and "`priority=low` re-verification item to `README-AUTHOR-TO-COMPLETE.md`"
          in readme
          and "MANUAL_STEPS.md" not in readme)
    check("the typo rule keeps a high-priority hand-off in every mode",
          "High priority" in doc and "High priority" in off
          and "priority is a row in `README-AUTHOR-TO-COMPLETE.md`" in readme)


def cleanup():
    for d in TMPDIRS:
        shutil.rmtree(d, ignore_errors=True)


def main() -> int:
    try:
        test_static()
        test_generated_prompts()
        test_manual_counter()
        test_mode_destinations()
    finally:
        cleanup()
    print()
    if FAILS:
        print(f"{len(FAILS)} FAILURE(S): " + "; ".join(FAILS))
        return 1
    print("ALL INFERABLE-TYPO POLICY CHECKS PASSED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
